/**
 * The tuner runs in an AudioWorklet. The source is a string so the phone
 * does not need a separate worker file in the webpack build, and the tests
 * can run the same class.
 * Pitch is a small YIN. The shift reads the delay at target/detected so a
 * sharp note moves down, not further up. The recorded sample stays on that
 * tuned waveform even when one crossfade sample dips quieter than the dry.
 */
const TUNER_SOURCE = [
    'class SplashTuner extends AudioWorkletProcessor {',
    '  constructor() {',
    '    super();',
    '    this.strength = 0.75;',
    '    this.bypass = 0;',
    '    this.mask = [1,0,1,0,1,1,0,1,0,1,0,1];',
    '    this.ring = new Float32Array(4096);',
    '    this.write = 0;',
    '    this.phase = 0;',
    '    this.ratio = 1;',
    '    this.period = 256;',
    '    this.dryEnv = 0;',
    '    this.tuneEnv = 0;',
    '    this.since = 0;',
    '    this.recording = false;',
    '    this.delay = 0;',
    '    this.collect = new Float32Array(2048);',
    '    this.collectN = 0;',
    '    this.diff = new Float32Array(700);',
    '    this.cmnd = new Float32Array(700);',
    '    var self = this;',
    '    this.port.onmessage = function (event) {',
    '      var data = event.data || {};',
    '      if (data.type === "config") {',
    '        if (typeof data.strength === "number") self.strength = data.strength;',
    '        self.bypass = data.bypass ? 1 : 0;',
    '        if (data.mask && data.mask.length === 12) self.mask = data.mask;',
    '      } else if (data.type === "record") {',
    '        self.recording = !!data.on;',
    '        self.delay = data.delaySamples > 0 ? data.delaySamples : 0;',
    '      }',
    '    };',
    '  }',
    '  yin(sampleRate) {',
    '    var len = 1024;',
    '    var tauMax = Math.min((sampleRate / 70) | 0, 680);',
    '    var tauMin = (sampleRate / 800) | 0;',
    '    var start = (this.write - len) & 4095;',
    '    var diff = this.diff;',
    '    for (var tau = 1; tau <= tauMax; tau++) {',
    '      var sum = 0;',
    '      for (var i = 0; i < len - tau; i += 2) {',
    '        var a = this.ring[(start + i) & 4095];',
    '        var b = this.ring[(start + i + tau) & 4095];',
    '        var d = a - b;',
    '        sum += d * d;',
    '      }',
    '      diff[tau] = sum;',
    '    }',
    '    var cmnd = this.cmnd;',
    '    cmnd[0] = 1;',
    '    var run = 0;',
    '    for (var t = 1; t <= tauMax; t++) {',
    '      run += diff[t];',
    '      cmnd[t] = run > 0 ? diff[t] * t / run : 1;',
    '    }',
    '    var tau = tauMin;',
    '    while (tau < tauMax && cmnd[tau] > 0.15) tau++;',
    '    if (tau >= tauMax || cmnd[tau] > 0.15) return 0;',
    '    while (tau + 1 <= tauMax && cmnd[tau + 1] < cmnd[tau]) tau++;',
    '    var x0 = cmnd[tau - 1] || cmnd[tau];',
    '    var x1 = cmnd[tau];',
    '    var x2 = cmnd[tau + 1] || cmnd[tau];',
    '    var denom = 2 * x1 - x2 - x0;',
    '    var better = denom === 0 ? tau : tau + (x2 - x0) / (2 * denom);',
    '    if (!(better > 1)) return 0;',
    '    return sampleRate / better;',
    '  }',
    '  retune(freq) {',
    '    if (!(freq > 0)) return 1;',
    '    var midi = 69 + 12 * Math.log(freq / 440) / Math.LN2;',
    '    var base = Math.round(midi);',
    '    var best = midi;',
    '    var dist = 100;',
    '    for (var n = base - 6; n <= base + 6; n++) {',
    '      var pc = ((n % 12) + 12) % 12;',
    '      if (!this.mask[pc]) continue;',
    '      var gap = Math.abs(n - midi);',
    '      if (gap < dist) { dist = gap; best = n; }',
    '    }',
    '    var target = 440 * Math.pow(2, (best - 69) / 12);',
    '    var full = target / freq;',
    '    var amount = this.strength;',
    '    if (amount < 0) amount = 0;',
    '    if (amount > 1) amount = 1;',
    '    return 1 + amount * (full - 1);',
    '  }',
    '  process(inputs, outputs) {',
    '    var input = inputs[0] && inputs[0][0];',
    '    var channels = outputs[0];',
    '    var output = channels && channels[0];',
    '    if (!input || !output) return true;',
    '    try {',
    '    for (var i = 0; i < input.length; i++) {',
    '      var dry = input[i];',
    '      this.ring[this.write] = dry;',
    '      this.write = (this.write + 1) & 4095;',
    '      this.since++;',
    '      var wet = dry;',
    '      if (!this.bypass && this.strength > 0.001 && Math.abs(this.ratio - 1) > 0.002) {',
    '        var hop = this.period > 40 ? this.period : 256;',
    '        if (hop > 700) hop = 700;',
    '        this.phase += this.ratio - 1;',
    '        if (this.phase >= hop) this.phase -= hop;',
    '        if (this.phase < 0) this.phase += hop;',
    '        var p = this.phase;',
    '        var i0 = (this.write - hop * 2 + p) & 4095;',
    '        var i1 = (i0 + hop) & 4095;',
    '        var fade = p / hop;',
    '        wet = this.ring[i0] * (1 - fade) + this.ring[i1] * fade;',
    '      }',
    '      var y = this.bypass ? dry : dry * (1 - this.strength) + wet * this.strength;',
    '      if (y !== y) y = dry;',
    '      for (var c = 0; c < channels.length; c++) channels[c][i] = y;',
    '      if (this.delay > 0) {',
    '        this.delay -= 1;',
    '      } else if (this.recording) {',
    '        this.dryEnv = this.dryEnv * 0.98 + Math.abs(dry) * 0.02;',
    '        this.tuneEnv = this.tuneEnv * 0.98 + Math.abs(y) * 0.02;',
    '        var kept = y;',
    '        if (this.bypass || this.strength <= 0.001) kept = dry;',
    '        else if (this.tuneEnv < this.dryEnv * 0.2 && this.dryEnv > 0.004) kept = dry;',
    '        else if (this.tuneEnv > 0.00008 && this.tuneEnv < this.dryEnv * 0.9) {',
    '          var lift = this.dryEnv / this.tuneEnv;',
    '          if (lift > 2.5) lift = 2.5;',
    '          kept = y * lift;',
    '        }',
    '        this.collect[this.collectN++] = kept;',
    '      }',
    '    }',
    '    if (this.collectN > 0) {',
    '      var copy = new Float32Array(this.collect.subarray(0, this.collectN));',
    '      this.port.postMessage({ type: "chunk", samples: copy }, [copy.buffer]);',
    '      this.collectN = 0;',
    '    }',
    '    if (this.since >= 1024) {',
    '      this.since = 0;',
    '      var next = 1;',
    '      var detected = 0;',
    '      try {',
    '        detected = this.yin(sampleRate);',
    '        next = this.bypass ? 1 : this.retune(detected);',
    '      } catch (err) { next = 1; }',
    '      if (detected > 70) {',
    '        var period = (sampleRate / detected) | 0;',
    '        if (period < 32) period = 32;',
    '        if (period > 600) period = 600;',
    '        this.period = period;',
    '      }',
    '      if (!(next > 0.5 && next < 2)) next = 1;',
    '      this.ratio += (next - this.ratio) * 0.55;',
    '    }',
    '    } catch (err) {',
    '      for (var k = 0; k < input.length; k++) {',
    '        for (var ch = 0; ch < channels.length; ch++) channels[ch][k] = input[k];',
    '      }',
    '    }',
    '    return true;',
    '  }',
    '}',
    'registerProcessor("splash-tuner", SplashTuner);',
].join('\n')

module.exports = { TUNER_SOURCE }
